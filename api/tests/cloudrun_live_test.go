package tests

import (
	"bytes"
	"encoding/json"
	"io"
	"net/http"
	"os"
	"strings"
	"testing"
	"time"
)

func getBaseURL() string {
	if u := os.Getenv("TARGET_URL"); u != "" {
		return strings.TrimRight(u, "/")
	}
	// Deployed Cloud Run instance URL
	return "https://fontokmai-api-lmr33aj5zq-as.a.run.app"
}

func doRequest(t *testing.T, method, path string, demoClock string, reqBody any) (int, map[string]any, time.Duration) {
	t.Helper()
	var r io.Reader
	if reqBody != nil {
		b, err := json.Marshal(reqBody)
		if err != nil {
			t.Fatalf("failed to marshal request: %v", err)
		}
		r = bytes.NewReader(b)
	}

	req, err := http.NewRequest(method, getBaseURL()+path, r)
	if err != nil {
		t.Fatalf("failed to create request: %v", err)
	}
	if reqBody != nil {
		req.Header.Set("Content-Type", "application/json")
	}
	if demoClock != "" {
		req.Header.Set("X-Demo-Clock", demoClock)
	}

	start := time.Now()
	client := &http.Client{Timeout: 30 * time.Second}
	resp, err := client.Do(req)
	duration := time.Since(start)
	if err != nil {
		t.Fatalf("request %s %s failed: %v", method, path, err)
	}
	defer resp.Body.Close()

	bodyBytes, err := io.ReadAll(resp.Body)
	if err != nil {
		t.Fatalf("failed to read response body: %v", err)
	}

	var jsonResp map[string]any
	if len(bodyBytes) > 0 && resp.StatusCode == http.StatusOK {
		if err := json.Unmarshal(bodyBytes, &jsonResp); err != nil {
			t.Fatalf("failed to unmarshal JSON response (status %d): %s, err: %v", resp.StatusCode, string(bodyBytes), err)
		}
	}
	return resp.StatusCode, jsonResp, duration
}

func TestCloudRun_Healthz(t *testing.T) {
	// Checks if the server root or health probe responds
	status, _, duration := doRequest(t, http.MethodGet, "/healthz", "", nil)
	if status == http.StatusNotFound {
		t.Logf("Note: /healthz returned 404 on current revision, falling back to /v1/places check")
		status, _, duration = doRequest(t, http.MethodGet, "/v1/places", "", nil)
	}
	t.Logf("Health check responded in %v with status %d", duration, status)
	if status != http.StatusOK {
		t.Fatalf("expected status 200, got %d", status)
	}
}

func TestCloudRun_Places(t *testing.T) {
	status, body, duration := doRequest(t, http.MethodGet, "/v1/places", "", nil)
	t.Logf("GET /v1/places responded in %v with status %d", duration, status)
	if status != http.StatusOK {
		t.Fatalf("expected status 200, got %d", status)
	}
	places, ok := body["places"].([]any)
	if !ok || len(places) == 0 {
		t.Fatalf("expected non-empty places array, got %v", body["places"])
	}
	t.Logf("Found %d places. Current place: %v", len(places), body["current_place_id"])
}

func TestCloudRun_Decide_PreTripCheck(t *testing.T) {
	// 16:10 Car trip check (Dinner at Ladprao)
	req := map[string]any{
		"trip_id": "cal-dinner",
		"mode":    "car",
	}
	status, body, duration := doRequest(t, http.MethodPost, "/v1/decide", "16:10", req)
	t.Logf("POST /v1/decide (16:10 Car) responded in %v (Status %d)", duration, status)

	if status != http.StatusOK {
		t.Fatalf("expected status 200, got %d (body: %+v)", status, body)
	}

	generatedBy, _ := body["generated_by"].(string)
	verdict, _ := body["verdict"].(string)
	headline, _ := body["headline_th"].(string)
	summary, _ := body["summary_th"].(string)

	t.Logf("-> Generated By : %s", generatedBy)
	t.Logf("-> Verdict      : %s", verdict)
	t.Logf("-> Headline TH  : %s", headline)
	t.Logf("-> Summary TH   : %s", summary)
	t.Logf("-> Latency      : %v", duration)

	if verdict == "" {
		t.Errorf("expected a valid verdict, got empty string")
	}
	if headline == "" {
		t.Errorf("expected a Thai headline, got empty string")
	}

	// Check reasoning tool calls
	if reasoning, ok := body["reasoning"].([]any); ok {
		t.Logf("-> Reasoning Trace (%d tool calls):", len(reasoning))
		for i, call := range reasoning {
			if c, ok := call.(map[string]any); ok {
				t.Logf("   [%d] Tool: %-22s -> %s", i+1, c["tool"], c["summary_th"])
			}
		}
	}
}

